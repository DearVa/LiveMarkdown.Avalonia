using System.Net;
using System.Net.NetworkInformation;
using System.Net.Sockets;

namespace LiveMarkdown.Avalonia.Demo.Links.Preview;

internal static class PreviewTransport
{
    private static readonly IPNetwork[] ReservedNetworks = [
        IPNetwork.Parse("0.0.0.0/8"),
        IPNetwork.Parse("10.0.0.0/8"),
        IPNetwork.Parse("100.64.0.0/10"),
        IPNetwork.Parse("127.0.0.0/8"),
        IPNetwork.Parse("169.254.0.0/16"),
        IPNetwork.Parse("172.16.0.0/12"),
        IPNetwork.Parse("192.0.0.0/24"),
        IPNetwork.Parse("192.0.2.0/24"),
        IPNetwork.Parse("192.88.99.0/24"),
        IPNetwork.Parse("192.168.0.0/16"),
        IPNetwork.Parse("198.18.0.0/15"),
        IPNetwork.Parse("198.51.100.0/24"),
        IPNetwork.Parse("203.0.113.0/24"),
        IPNetwork.Parse("224.0.0.0/3"),
        IPNetwork.Parse("2001::/23"),
        IPNetwork.Parse("2001:db8::/32"),
        IPNetwork.Parse("2002::/16"),
        IPNetwork.Parse("3fff::/20"),
    ];
    private static readonly IPNetwork GlobalUnicastV6 = IPNetwork.Parse("2000::/3");

    public static HttpClient CreateClient()
    {
        return new HttpClient(new SocketsHttpHandler
        {
            AllowAutoRedirect = false,
            AutomaticDecompression = DecompressionMethods.GZip | DecompressionMethods.Deflate | DecompressionMethods.Brotli,
            UseCookies = false,
            MaxResponseHeadersLength = 32,
            MaxResponseDrainSize = 0,
            ConnectTimeout = TimeSpan.FromSeconds(3),
            PooledConnectionLifetime = TimeSpan.FromMinutes(2),
            ConnectCallback = ConnectAsync,
        })
        {
            Timeout = Timeout.InfiniteTimeSpan,
        };
    }

    public static bool IsAllowed(Uri uri)
    {
        if (!uri.IsAbsoluteUri || uri.Scheme is not ("http" or "https") ||
            !uri.IsDefaultPort || uri.UserInfo.Length != 0 || uri.AbsoluteUri.Length > 4096)
        {
            return false;
        }

        var host = uri.IdnHost.TrimEnd('.');
        if (IPAddress.TryParse(host, out var address))
        {
            return IsPublic(address);
        }

        return uri.HostNameType == UriHostNameType.Dns && host.Contains('.') &&
            !host.EndsWith(".localhost", StringComparison.OrdinalIgnoreCase) &&
            !host.EndsWith(".local", StringComparison.OrdinalIgnoreCase) &&
            !host.EndsWith(".home.arpa", StringComparison.OrdinalIgnoreCase);
    }

    public static bool IsPublic(IPAddress address)
    {
        if (address.IsIPv4MappedToIPv6)
        {
            address = address.MapToIPv4();
        }

        if (address.AddressFamily == AddressFamily.InterNetworkV6 && (address.ScopeId != 0 || !GlobalUnicastV6.Contains(address)))
        {
            return false;
        }

        return !ReservedNetworks.Any(network => network.Contains(address));
    }

    private static async ValueTask<Stream> ConnectAsync(SocketsHttpConnectionContext context, CancellationToken cancellationToken)
    {
        var endpoint = context.DnsEndPoint;
        var request = context.InitialRequestMessage;
        var socket = new Socket(SocketType.Stream, ProtocolType.Tcp) { NoDelay = true };
        try
        {
            // CONNECT is generated by HttpClient for HTTPS proxy tunnels. Forward HTTP and
            // SOCKS connections also use the proxy's TCP endpoint instead of the request origin.
            if (request.Method == HttpMethod.Connect ||
                (request.RequestUri is { } origin &&
                 (!endpoint.Host.Equals(origin.IdnHost, StringComparison.OrdinalIgnoreCase) || endpoint.Port != origin.Port)))
            {
                await socket.ConnectAsync(endpoint, cancellationToken).ConfigureAwait(false);
            }
            else
            {
                var addresses = await ResolvePublicAddressesAsync(endpoint.Host, cancellationToken).ConfigureAwait(false);
                // Pin the checked address for direct requests; normal TLS hostname validation remains in HttpClient.
                await socket.ConnectAsync(addresses, endpoint.Port, cancellationToken).ConfigureAwait(false);
            }

            return new NetworkStream(socket, ownsSocket: true);
        }
        catch
        {
            socket.Dispose();
            throw;
        }
    }

    private static async Task<IPAddress[]> ResolvePublicAddressesAsync(string host, CancellationToken cancellationToken)
    {
        var addresses = IPAddress.TryParse(host, out var literal)
            ? [literal]
            : await Dns.GetHostAddressesAsync(host.TrimEnd('.') + ".", cancellationToken).ConfigureAwait(false);
        var localAddresses = NetworkInterface.GetAllNetworkInterfaces()
            .SelectMany(adapter => adapter.GetIPProperties().UnicastAddresses)
            .Select(info => info.Address)
            .ToHashSet();
        if (addresses.Length == 0 || addresses.Any(address => !IsPublic(address) ||
            localAddresses.Contains(address.IsIPv4MappedToIPv6 ? address.MapToIPv4() : address)))
        {
            throw new HttpRequestException("A preview target resolved to a non-public or local address.");
        }

        return addresses;
    }
}
